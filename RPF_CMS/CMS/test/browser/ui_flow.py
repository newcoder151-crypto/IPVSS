CMS = os.environ.get('CMS_URL', 'http://localhost:7080'); RPF = os.environ.get('RPF_URL', 'http://localhost:7090')
problems = []
def ok(c, m):
    print(('  ok   - ' if c else '  FAIL - ') + m)
    if not c: problems.append(m)

def sim(*args, bg=False):
    env = dict(os.environ, CODEC='vp9')
    cmd = ['node', os.path.join(ROOT, 'scripts', 'mnvr_sim.js'), *args]
    return subprocess.Popen(cmd, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL) if bg else subprocess.run(cmd, env=env, capture_output=True, text=True, cwd=ROOT)

def cms_setting(**kv):
    import urllib.request
    def call(path, body, method='POST', tok=None):
        req = urllib.request.Request(CMS + '/console/api' + path, data=json.dumps(body).encode(), method=method, headers={'Content-Type': 'application/json', **({'Authorization': 'Bearer ' + tok} if tok else {})})
        return json.loads(urllib.request.urlopen(req).read())
    tok = call('/auth/login', {'username': 'cms-super', 'password': 'cms-demo-123'})['token']
    call('/settings', kv, 'PUT', tok)

